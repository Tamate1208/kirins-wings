function drawCard() {
  const index = Math.floor(Math.random() * MAJOR_ARCANA.length);
  const card = MAJOR_ARCANA[index];
  const isUpright = Math.random() >= 0.35; // 65% 正位置
  return {
    ...card,
    isUpright,
    orientation: isUpright ? "正位置 (Upright)" : "逆位置 (Reversed)",
    detail: isUpright ? card.upright : card.reversed
  };
}

